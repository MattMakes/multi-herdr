use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let crate_dir = Path::new(&manifest_dir);
    let root = crate_dir.parent().unwrap().parent().unwrap();
    let teammates = root.join("teammates");

    println!("cargo:rerun-if-changed={}", teammates.display());
    println!(
        "cargo:rerun-if-changed={}",
        teammates.join("_base").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        teammates.join("system_prompt").display()
    );
    println!("cargo:rerun-if-changed=build.rs");

    let mut out = String::new();
    out.push_str("// @generated by build.rs from teammates/. Do not edit.\n");

    emit(&mut out, "BUILTIN_TEAMMATES", &teammates, |name| {
        !name.starts_with('_')
    });
    emit(&mut out, "BUILTIN_BASES", &teammates.join("_base"), |_| {
        true
    });
    emit(
        &mut out,
        "BUILTIN_SYSTEM_PROMPTS",
        &teammates.join("system_prompt"),
        |_| true,
    );

    let template = teammates.join("_template.md");
    println!("cargo:rerun-if-changed={}", template.display());
    writeln!(
        out,
        "pub static TEMPLATE: &str = include_str!(r\"{}\");",
        template.display()
    )
    .unwrap();

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("builtin_teammates.rs");
    std::fs::write(dest, out).unwrap();

    let skills = root.join("skills");
    println!("cargo:rerun-if-changed={}", skills.display());
    let mut files = Vec::new();
    if skills.exists() {
        collect_skill_files(&skills, &skills, &mut files);
    }
    files.sort();
    let mut bundled = String::from("pub static BUNDLED_SKILL_FILES: &[(&str, &[u8])] = &[\n");
    for (relative, absolute) in &files {
        writeln!(bundled, "    ({relative:?}, include_bytes!({absolute:?})),").unwrap();
    }
    bundled.push_str("];\n");
    let executable: Vec<&str> = files
        .iter()
        .filter(|(_, absolute)| is_executable(Path::new(absolute)))
        .map(|(relative, _)| relative.as_str())
        .collect();
    bundled.push_str("pub static BUNDLED_SKILL_EXECUTABLES: &[&str] = &[\n");
    for relative in &executable {
        writeln!(bundled, "    {relative:?},").unwrap();
    }
    bundled.push_str("];\n");
    bundled.push_str("pub(crate) static BUNDLED_SKILL_DIGESTS: &[(&str, [u8; 32])] = &[\n");
    for (name, digest) in skill_digests(&files, &executable) {
        writeln!(bundled, "    ({name:?}, {digest:?}),").unwrap();
    }
    bundled.push_str("];\n");
    let copied = skills.join("copied.json");
    println!("cargo:rerun-if-changed={}", copied.display());
    writeln!(
        bundled,
        "pub static BUNDLED_COPIED: &str = include_str!({:?});",
        copied.to_string_lossy()
    )
    .unwrap();
    std::fs::write(
        Path::new(&std::env::var("OUT_DIR").unwrap()).join("bundled_skills.rs"),
        bundled,
    )
    .unwrap();
}

fn is_executable(path: &Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::metadata(path).unwrap().permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        false
    }
}

pub(crate) fn skill_digests(
    files: &[(String, String)],
    executable: &[&str],
) -> Vec<(String, [u8; 32])> {
    files
        .iter()
        .filter_map(|(relative, _)| relative.strip_suffix("/SKILL.md"))
        .filter(|name| !name.contains('/'))
        .map(|name| (name.to_owned(), tree_digest(name, files, executable)))
        .collect()
}

fn tree_digest(name: &str, files: &[(String, String)], executable: &[&str]) -> [u8; 32] {
    use sha2::{Digest as _, Sha256};
    let prefix = format!("{name}/");
    let mut lines: Vec<(&str, String, bool)> = files
        .iter()
        .filter_map(|(relative, absolute)| {
            let rel = relative.strip_prefix(&prefix)?;
            let bytes = std::fs::read(absolute).unwrap();
            let hash: String = Sha256::digest(&bytes)
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect();
            Some((rel, hash, executable.contains(&relative.as_str())))
        })
        .collect();
    lines.sort();
    let mut tree = Sha256::new();
    for (rel, hash, exec) in &lines {
        tree.update(rel.as_bytes());
        tree.update([0u8]);
        tree.update(hash.as_bytes());
        if *exec {
            tree.update(b"\0x");
        }
        tree.update(b"\n");
    }
    tree.finalize().into()
}

fn collect_skill_files(root: &Path, dir: &Path, files: &mut Vec<(String, String)>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        let kind = entry.file_type().unwrap();
        assert!(
            !kind.is_symlink(),
            "bundled skills must not depend on symlinks"
        );
        let path = entry.path();
        if kind.is_dir() {
            collect_skill_files(root, &path, files);
        } else if kind.is_file() {
            let relative = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            files.push((relative, path.to_string_lossy().into_owned()));
        }
    }
}

fn emit(out: &mut String, ident: &str, dir: &Path, keep: fn(&str) -> bool) {
    let mut entries: Vec<(String, String)> = Vec::new();
    if let Ok(read) = std::fs::read_dir(dir) {
        for entry in read.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("md") {
                continue;
            }
            let stem = path.file_stem().unwrap().to_string_lossy().to_string();
            if stem == "README" || !keep(&stem) {
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            entries.push((stem, path.display().to_string()));
        }
    }
    entries.sort();

    writeln!(out, "pub(crate) static {ident}: &[(&str, &str)] = &[").unwrap();
    for (stem, path) in entries {
        writeln!(out, "    (\"{stem}\", include_str!(r\"{path}\")),").unwrap();
    }
    out.push_str("];\n");
}
